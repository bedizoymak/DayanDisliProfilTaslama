/**
 * Reproduces the production-receipt PDFs generated by jsPDF + jspdf-autotable in
 * SpurGearReceipt.tsx / HelicalGearReceipt.tsx, using Android's native PdfDocument/Canvas so no
 * third-party PDF library is required. Roboto (res/font/roboto_regular.ttf, roboto_bold.ttf —
 * the same TTFs the web app embeds into its jsPDF VFS) provides Turkish, Greek and math glyph
 * coverage (ç, ş, ı, ğ, ü, ö, α, β, °, ø).
 */
object PdfReceiptGenerator {
    private const val PAGE_WIDTH = 595 // A4 at 72dpi, matches jsPDF's default "pt" unit page
    private const val PAGE_HEIGHT = 842
    private const val MARGIN = 40f

    private val BLUE_HEADER = Color.rgb(41, 128, 185)
    private val PURPLE_HEADER = Color.rgb(147, 51, 234)

    private fun regularTypeface(context: Context) = ResourcesCompat.getFont(context, R.font.roboto_regular)
    private fun boldTypeface(context: Context) = ResourcesCompat.getFont(context, R.font.roboto_bold)

    fun renderSpurReceiptPdf(
        context: Context,
        machine: Machine,
        result: SpurGearResult,
        combinations: List<GearCombination>,
    ): ByteArray {
        val doc = PdfDocument()
        val painter = ReceiptPainter(context, doc, BLUE_HEADER)
        painter.newPage()
        painter.drawTitle("Düz Dişli Üretim Reçetesi")
        painter.drawSubtitle("Makine: ${machine.name}")

        painter.drawTable(
            headers = listOf("Parametre", "Değer"),
            rows = listOf(
                listOf("Modül (mn)", result.mn.toFixedJs(4)),
                listOf("Diş Sayısı (Z)", result.z.toString()),
                listOf("Kavrama Açısı (α)", "${result.alphaDeg.toFixedJs(2)}°"),
                listOf("Çap (ø)", "${result.diameter.toFixedJs(2)} mm"),
                listOf("Wk (k=${result.kFloor})", "${result.wkFloor.toFixedJs(4)} mm"),
                listOf("Wk (k=${result.kCeil})", "${result.wkCeil.toFixedJs(4)} mm"),
                listOf("Taksimat Oranı", result.taksimatRatio.toFixedJs(6)),
            ),
        )

        painter.drawSectionTitle("Taksimat Çark Kombinasyonları")
        painter.drawTable(
            headers = listOf("A", "B", "C", "D"),
            rows = combinations.map { comboRow(it) },
        )

        painter.drawFooter()
        painter.finish()
        return doc.toByteArray()
    }

    fun renderHelicalReceiptPdf(
        context: Context,
        machine: Machine,
        result: HelicalGearResult,
        taksimatCombinations: List<GearCombination>,
        helicalCombinations: List<GearCombination>,
    ): ByteArray {
        val doc = PdfDocument()
        val painter = ReceiptPainter(context, doc, PURPLE_HEADER)
        painter.newPage()
        painter.drawTitle("Helisel Dişli Üretim Reçetesi")
        painter.drawSubtitle("Makine: ${machine.name}")

        painter.drawTable(
            headers = listOf("Parametre", "Değer"),
            rows = listOf(
                listOf("Modül (mn)", result.mn.toFixedJs(4)),
                listOf("Diş Sayısı (Z)", result.z.toString()),
                listOf("Kavrama Açısı (α)", "${result.alphaDeg.toFixedJs(2)}°"),
                listOf("Helis Açısı (β)", "${result.betaDeg.toFixedJs(2)}°"),
                listOf("Helis Yönü", result.helixDirection.label),
                listOf("Çap (ø)", "${result.diameter.toFixedJs(2)} mm"),
                listOf("Wk (k=${result.kFloor})", "${result.wkFloor.toFixedJs(4)} mm"),
                listOf("Wk (k=${result.kCeil})", "${result.wkCeil.toFixedJs(4)} mm"),
                listOf("Taksimat Oranı", result.taksimatRatio.toFixedJs(6)),
                listOf("Helis Çark Oranı", result.helicalGearRatio.toFixedJs(6)),
            ),
        )

        painter.drawSectionTitle("Taksimat Çark Kombinasyonları")
        painter.drawTable(
            headers = listOf("A", "B", "C", "D"),
            rows = if (taksimatCombinations.isNotEmpty()) taksimatCombinations.map { comboRow(it) } else listOf(listOf("-", "-", "-", "-")),
        )

        painter.drawSectionTitle("Helis Çark Kombinasyonları")
        painter.drawTable(
            headers = listOf("A", "B", "C", "D"),
            rows = if (helicalCombinations.isNotEmpty()) helicalCombinations.map { comboRow(it) } else listOf(listOf("-", "-", "-", "-")),
        )

        painter.drawFooter()
        painter.finish()
        return doc.toByteArray()
    }

