    private fun comboRow(c: GearCombination): List<String> =
        listOf(c.a.toString(), c.b.toString(), c.c?.toString() ?: "-", c.d?.toString() ?: "-")

    private fun PdfDocument.toByteArray(): ByteArray {
        val out = ByteArrayOutputStream()
        writeTo(out)
        close()
        return out.toByteArray()
    }

    /** Writes [bytes] to the app cache and returns a FileProvider content Uri, then opens the
     * system share sheet (which includes "Save to..." targets, covering the SAF save path too). */
    fun shareBytes(context: Context, bytes: ByteArray, fileName: String) {
        val uri = writeToCache(context, bytes, fileName)
        val intent = Intent(Intent.ACTION_SEND).apply {
            type = "application/pdf"
            putExtra(Intent.EXTRA_STREAM, uri)
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        }
        val chooser = Intent.createChooser(intent, "Reçeteyi Paylaş / Kaydet")
        if (context !is android.app.Activity) {
            chooser.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
        }
        context.startActivity(chooser)
    }

    private fun writeToCache(context: Context, bytes: ByteArray, fileName: String): android.net.Uri {
        val pdfDir = File(context.cacheDir, "pdf").apply { mkdirs() }
        val file = File(pdfDir, "$fileName.pdf")
        file.writeBytes(bytes)
        return FileProvider.getUriForFile(context, "com.dayandisli.calculator.fileprovider", file)
    }

    /** Prints via Android's PrintManager without requiring broad storage permissions. */
    fun printBytes(context: Context, bytes: ByteArray, jobName: String) {
        val printManager = context.getSystemService(Context.PRINT_SERVICE) as PrintManager
        val adapter = object : android.print.PrintDocumentAdapter() {
            override fun onLayout(
                oldAttributes: PrintAttributes?,
                newAttributes: PrintAttributes,
                cancellationSignal: android.os.CancellationSignal?,
                callback: LayoutResultCallback,
                extras: android.os.Bundle?,
            ) {
                if (cancellationSignal?.isCanceled == true) {
                    callback.onLayoutCancelled()
                    return
                }
                val info = android.print.PrintDocumentInfo.Builder("$jobName.pdf")
                    .setContentType(android.print.PrintDocumentInfo.CONTENT_TYPE_DOCUMENT)
                    .build()
                callback.onLayoutFinished(info, oldAttributes != newAttributes)
            }

            override fun onWrite(
                pages: Array<out android.print.PageRange>?,
                destination: android.os.ParcelFileDescriptor,
                cancellationSignal: android.os.CancellationSignal?,
                callback: WriteResultCallback,
            ) {
                try {
                    java.io.FileOutputStream(destination.fileDescriptor).use { it.write(bytes) }
                    callback.onWriteFinished(arrayOf(android.print.PageRange.ALL_PAGES))
                } catch (e: java.io.IOException) {
                    callback.onWriteFailed(e.message)
                }
            }
        }
        printManager.print(jobName, adapter, android.print.PrintAttributes.Builder().build())
    }

    /** Handles the drawing/pagination for a single receipt document. */
    private class ReceiptPainter(context: Context, private val doc: PdfDocument, private val headerColor: Int) {
        private val regular = regularTypeface(context)
        private val bold = boldTypeface(context)
        private var page: PdfDocument.Page? = null
        private var canvas: Canvas? = null
        private var y = MARGIN

        fun newPage() {
            page?.let { doc.finishPage(it) }
            val newPageInfo = PdfDocument.PageInfo.Builder(PAGE_WIDTH, PAGE_HEIGHT, doc.pages.size + 1).create()
            val newPage = doc.startPage(newPageInfo)
            page = newPage
            canvas = newPage.canvas
            y = MARGIN
        }

        private fun ensureSpace(height: Float) {
            if (y + height > PAGE_HEIGHT - MARGIN) {
                newPage()
            }
        }

        fun drawTitle(text: String) {
            val paint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
                typeface = bold
                textSize = 18f
                textAlign = Paint.Align.CENTER
                color = Color.BLACK
            }
            canvas!!.drawText(text, PAGE_WIDTH / 2f, y + 18f, paint)
            y += 30f
        }

        fun drawSubtitle(text: String) {
            val paint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
                typeface = regular
                textSize = 12f
                textAlign = Paint.Align.CENTER
                color = Color.DKGRAY
            }
            canvas!!.drawText(text, PAGE_WIDTH / 2f, y, paint)
            y += 24f
        }

        fun drawSectionTitle(text: String) {
            ensureSpace(40f)
            y += 12f
            val paint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
                typeface = bold
                textSize = 13f
                textAlign = Paint.Align.CENTER
                color = Color.BLACK
            }
            canvas!!.drawText(text, PAGE_WIDTH / 2f, y, paint)
            y += 18f
        }

        fun drawFooter() {
            val paint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
                typeface = regular
                textSize = 9f
                textAlign = Paint.Align.CENTER
                color = Color.GRAY
            }
            canvas!!.drawText("DAYAN CALCULATOR - Dayan Dişli Sanayi", PAGE_WIDTH / 2f, PAGE_HEIGHT - 20f, paint)
        }

        fun drawTable(headers: List<String>, rows: List<List<String>>) {
            val tableWidth = PAGE_WIDTH - 2 * MARGIN
            val colWidth = tableWidth / headers.size
            val rowHeight = 24f

            val headerPaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
                typeface = bold
                textSize = 11f
                textAlign = Paint.Align.CENTER
                color = Color.WHITE
            }
            val cellPaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
                typeface = regular
                textSize = 10.5f
                textAlign = Paint.Align.CENTER
                color = Color.BLACK
            }
            val borderPaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
                style = Paint.Style.STROKE
                strokeWidth = 0.75f
                color = Color.LTGRAY
            }
            val headerFillPaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
                style = Paint.Style.FILL
                color = headerColor
            }

            ensureSpace(rowHeight)
            drawTableRow(headers, MARGIN, y, colWidth, rowHeight, headerFillPaint, headerPaint, borderPaint)
            y += rowHeight

            rows.forEach { row ->
                ensureSpace(rowHeight)
                drawTableRow(row, MARGIN, y, colWidth, rowHeight, null, cellPaint, borderPaint)
                y += rowHeight
            }
        }

        private fun drawTableRow(
            cells: List<String>,
            startX: Float,
            startY: Float,
            colWidth: Float,
            rowHeight: Float,
            fillPaint: Paint?,
            textPaint: Paint,
            borderPaint: Paint,
        ) {
            val cv = canvas!!
            cells.forEachIndexed { index, cell ->
                val left = startX + index * colWidth
                val rect = RectF(left, startY, left + colWidth, startY + rowHeight)
                if (fillPaint != null) cv.drawRect(rect, fillPaint)
                cv.drawRect(rect, borderPaint)
                val textY = startY + rowHeight / 2f - (textPaint.descent() + textPaint.ascent()) / 2f
                cv.drawText(cell, left + colWidth / 2f, textY, textPaint)
            }
        }

        fun finish() {
            page?.let { doc.finishPage(it) }
        }
    }
}
